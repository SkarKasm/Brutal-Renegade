"""Regenerate sources.cmake from the VC6 project files (Code/*/*.dsp), so the CMake build
always compiles exactly what the original Release configuration compiled.

    py -3 Code/Port/gen_sources.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)

# CMake target -> .dsp (only what Renegade.exe needs)
PROJECTS = [
    ("wwdebug", "wwdebug/wwdebug.dsp"), ("wwlib", "wwlib/wwlib.dsp"), ("wwmath", "WWMath/wwmath.dsp"),
    ("wwsaveload", "wwsaveload/wwsaveload.dsp"), ("wwbitpack", "wwbitpack/wwbitpack.dsp"),
    ("wwtranslatedb", "wwtranslatedb/wwtranslatedb.dsp"), ("wwutil", "wwutil/wwutil.dsp"),
    ("wwnet", "wwnet/wwnet.dsp"), ("ww3d2", "ww3d2/ww3d2.dsp"), ("wwphys", "wwphys/wwphys.dsp"),
    ("wwaudio", "WWAudio/WWAudio.dsp"), ("wwui", "wwui/wwui.dsp"), ("combat", "Combat/Combat.dsp"),
    ("binkmovie", "BinkMovie/BinkMovie.dsp"), ("scontrol", "SControl/SControl.dsp"),
    ("commando", "Commando/commando.dsp"), ("scripts", "Scripts/Scripts.dsp"),
]


def release_sources(dsp_path):
    text = open(dsp_path, encoding="latin1").read().replace("\r\n", "\n")
    sources = []
    for m in re.finditer(r"# Begin Source File\s*\n\s*SOURCE=(.*?)\n(.*?)# End Source File", text, re.S):
        src, body = m.group(1).strip().strip('"'), m.group(2)
        rel = re.search(r'"\$\(CFG\)" == "[^"]* - Win32 Release"(.*?)(!ELSEIF|!ENDIF)', body, re.S)
        if rel and "PROP Exclude_From_Build 1" in rel.group(1):
            continue
        if not rel and "PROP Exclude_From_Build 1" in body and "!IF" not in body:
            continue
        if src.lower().endswith((".cpp", ".c", ".rc")):
            sources.append(src.replace("\\", "/"))
    return sources


lines = ["# Generated by gen_sources.py from the VC6 .dsp files. Do not edit by hand.", ""]
for target, dsp in PROJECTS:
    base = os.path.dirname(dsp)
    files = []
    for s in release_sources(os.path.join(CODE, dsp)):
        path = os.path.normpath(os.path.join(base, s)).replace("\\", "/")
        if not os.path.exists(os.path.join(CODE, path)):
            # VC6 paths are case-insensitive; find the real file name
            folder, name = os.path.split(path)
            real = next((f for f in os.listdir(os.path.join(CODE, folder)) if f.lower() == name.lower()), None)
            if real is None:
                lines.append("# missing: %s" % path)
                continue
            path = folder + "/" + real
        files.append("\t${RENEGADE_CODE}/" + path)
    lines.append("set(%s_SOURCES" % target.upper())
    lines.extend(files)
    lines.append(")")
    lines.append("")

open(os.path.join(HERE, "sources.cmake"), "w").write("\n".join(lines))
print("wrote sources.cmake")
